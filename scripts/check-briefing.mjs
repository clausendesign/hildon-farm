import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { answerQuestion, upcomingEvents, briefingScript } from '../public/briefing-answers.mjs';
import { nameFromSpeech } from '../public/farm-profile.mjs';
const brief = JSON.parse(readFileSync(new URL('../lib/market-seed.json', import.meta.url)));
const now = Date.parse('2026-10-23T20:00:00Z');
const answer = (q, c = {}) => answerQuestion(brief, q, c, now);
assert.equal(answer('When is the next sale?').intent, 'sales');
assert.match(answer('When is the next sale?').text, /29 Oct 2026.*11:30/);
assert.equal(answer('When is the next lamb sale?').species, 'lambs');
assert.match(answer('When is the next lamb sale?').text, /30 Oct 2026.*11:00/);
const price = answer('What are cattle prices?');
assert.match(price.text, /Historical observation/);
assert.match(price.text, /NZD\/kg LW/);
assert.match(price.text, /4 Sept? 2026/);
assert.match(price.text, /no recent, verified Feilding price/);
assert.match(answer('What are lamb prices?').text, /NZD\/head/);
assert.match(answer('How much are my 300kg steers worth?').text, /can’t value your animals/);
assert.match(answer('What are sheep prices?').text, /no verified sheep price/);
assert.match(answer('Are prices trending up?').text, /aren’t enough recent, comparable/);
assert.equal(answer('And what about lambs?', { species: 'cattle', intent: 'prices' }).intent, 'prices');
assert.equal(answer('And what about lambs?', { species: 'cattle', intent: 'prices' }).species, 'lambs');
assert.match(answer('What is the cattle outlook?').text, /uncertain, low confidence/);
assert.match(answer('Did the outlook hold up?').text, /no matched outcomes/);
assert.match(answer('What does firm mean?').text, /favours a seller/);
assert.match(answer('What about the weather?').text, /not a current forecast/);
assert.match(answer('What is the latest price of gold?').text, /I can help with the saved livestock briefing/);
assert.match(answer('Write me a poem').text, /saved livestock briefing/);
assert.equal(upcomingEvents(brief, 'all', Date.parse('2027-01-01')).length, 0);
const timed = { events: [{ date: '2026-10-24', time: '08:00', species: 'cattle' }, { date: '2026-10-24', time: '11:00', species: 'cattle' }] };
assert.equal(upcomingEvents(timed, 'cattle', Date.parse('2026-10-23T20:00:00Z')).length, 1);
assert.match(briefingScript(brief, 'Big Dog Wok', now), /Big Dog Wok/);
for (const [speech, name] of [['call me Wozza', 'Wozza'], ['Wok', 'Wok'], ['Big Dog Walk', 'Big Dog Wok'], ['Warwick please', 'Warwick']]) assert.equal(nameFromSpeech(speech), name);
assert.equal(nameFromSpeech('banana'), null);
for (const q of ['When is the next sale?', 'What are cattle prices?', 'What is the outlook?', 'What about the weather?']) {
  const a = answer(q);
  assert(a.sourceIds.every(id => brief.sources.some(s => s.id === id)));
}
console.log('Briefing checks passed: dates, units, missing evidence, follow-up questions, sources and spoken names.');
